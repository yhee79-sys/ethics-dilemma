// 위 규칙에 걸리지만 이 설문에서 의미 있는 명사
const NOUN_EXCEPTIONS = new Set([
  "배려", "격려", "이해", "오해", "피해", "손해", "신고", "충고", "경고", "사고", "최고", "참고", "의지", "처지",
  "약자", "강자", "의리", "언어", "아이", "보고", "가치", "자아", "부모", "선배", "후배", "똑같이",
]);

// "신고하는", "똑같이"처럼 어간 뒤에 바로 붙는 형태를 명사로 되돌린다
const STEM_FIXES: Record<string, string> = { 열심히: "열심", 상처받: "상처", 똑같: "똑같이", 나누: "나눔", 나눠: "나눔", 지키: "지킴", 속이: "속임" };

function stripSuffix(word: string, suffixes: string[]): string {
  for (const s of suffixes) {
    const rest = word.length - s.length;
    // "하-" 어미("말하는" → "말")와 "으로"("팀으로" → "팀")는 1글자만 남아도 떼고, 뒤에서 1글자 토큰으로 버린다
    const min = /^[하해했한할함으]/.test(s) ? 1 : 2;
    if (rest >= min && word.endsWith(s)) return word.slice(0, -s.length);
  }
  return word;
}

/** 한 단어를 정규화한다. 버릴 단어면 null */
export function normalizeToken(raw: string): string | null {
  let w = raw.toLowerCase();
  if (!COMPLETE_TOKEN.test(w)) return null; // 자모(ㅋㅋ), 기호 섞인 토큰
  if (BANNED.some((b) => w.includes(b))) return null;
  if (STOPWORDS.has(w)) return null;
  if (NOUN_EXCEPTIONS.has(w)) return w;
  w = stripSuffix(w, PARTICLES);
  if (NOUN_EXCEPTIONS.has(w)) return w;
  w = stripSuffix(w, VERB_ENDINGS);
  w = stripSuffix(w, PARTICLES); // "정직하다는" 처럼 어미 뒤에 조사가 남는 경우를 위해 한 번 더
  w = STEM_FIXES[w] ?? w;
  if (NOUN_EXCEPTIONS.has(w)) return w;
  if ([...w].length < 2) return null;
  if (/^\d+$/.test(w)) return null;
  if (STOPWORDS.has(w)) return null;
  if (PREDICATE_END.test(w)) return null;
  return w;
}

/** 한 응답에서 키워드 집합(중복 제거)을 뽑는다 */
export function extractTokens(text: string): Set<string> {
  const tokens = new Set<string>();
  for (const raw of text.replace(/[^가-힣ㄱ-ㅎㅏ-ㅣa-zA-Z0-9\s]/g, " ").split(/\s+/)) {
    const t = raw && normalizeToken(raw);
    if (t) tokens.add(t);
  }
  return tokens;
}

export type Keyword = { text: string; count: number };

/**
 * 여러 응답에서 키워드 빈도를 센다.
 * @param minCount 이 수 미만으로 언급된 단어는 버린다(한 사람만 쓴 단어로 개인이 드러나지 않도록)
 */
export function countKeywords(texts: string[], { limit = 40, minCount = 2 } = {}): Keyword[] {
  const counts = new Map<string, number>();
  for (const text of texts) {
    for (const t of extractTokens(text)) counts.set(t, (counts.get(t) ?? 0) + 1);
  }
  return [...counts.entries()]
    .filter(([, c]) => c >= minCount)
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0], "ko"))
    .slice(0, limit)
    .map(([text, count]) => ({ text, count }));
}
